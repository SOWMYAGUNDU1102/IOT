from sklearn.metrics import (
    accuracy_score,
    confusion_matrix,
    precision_score,
    recall_score,
    f1_score
)

# =========================================================
# LOAD DATASET
# =========================================================

data = pd.read_excel("vehicle_health_synthetic_dataset.xlsx")

# =========================================================
# FEATURES
# =========================================================

X = data[[
    'temperature',
    'current',
    'vibration',
    'voltage',
    'motor_speed',
    'load_percentage'
]]

